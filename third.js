truthBtn.addEventListener('click', function() {
    const randomTruth = truths[Math.floor(Math.random() * truths.length)];
    modalTitle.textContent = `${players[currentPlayerIndex]} - Truth`;
    modalTitle.style.color = "#1e90ff"; 
    modalQuestion.textContent = randomTruth;
    questionModal.style.display = "flex";
});

dareBtn.addEventListener('click', function() {
    const randomDare = dares[Math.floor(Math.random() * dares.length)];
    modalTitle.textContent = `${players[currentPlayerIndex]} - Dare`;
    modalTitle.style.color = "#ff1493"; 
    modalQuestion.textContent = randomDare;
    questionModal.style.display = "flex";
});

nextPlayerBtn.addEventListener('click', function() {
    questionModal.style.display = "none";
    currentPlayerIndex++;
    
    if (currentPlayerIndex >= players.length) {
        currentPlayerIndex = 0;
    }
    
    updateTurn();
});